export function buildInitialStudents(): Student[] {
  return RAW_STUDENTS.map((item) => {
    const subjectScores = item.scores.map((sc, idx) => ({
      subjectId: `sub-${item.department.toLowerCase()}-${idx + 1}`,
      subjectCode: sc.code,
      subjectName: sc.name,
      internal1: sc.int1,
      internal2: sc.int2,
      assignment: sc.assign,
      attendance: sc.att,
    }));

    const riskBreakdown = calculateRisk(subjectScores, item.overallAttendance, DEFAULT_SETTINGS);

    const studentPartial: Partial<Student> = {
      subjectScores,
      name: item.name,
      rollNumber: item.rollNumber,
    };

    return {
      id: item.id,
      rollNumber: item.rollNumber,
      name: item.name,
      email: item.email,
      department: item.department,
      semester: item.semester,
      section: item.section,
      mentorFacultyId: 'fac-1',
      mentorName: item.mentorName,
      overallAttendance: item.overallAttendance,
      subjectScores,
      riskCategory: riskBreakdown.category,
      riskScore: riskBreakdown.totalScore,
      riskBreakdown,
      previousRiskScore: Math.min(100, Math.max(0, riskBreakdown.totalScore - 6)),
      studyTasks: generateDefaultStudyPlan(studentPartial),
      academicYear: '2025-2026',
      phone: '+91 98765 ' + Math.floor(10000 + Math.random() * 90000),
      lastUpdated: new Date().toISOString(),
    };
  });
}

